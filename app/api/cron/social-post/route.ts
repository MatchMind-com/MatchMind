async function postToInstagram(caption: string): Promise<{ success: boolean; error?: string }> {
  const accessToken = process.env.INSTAGRAM_ACCESS_TOKEN
  const accountId = process.env.INSTAGRAM_BUSINESS_ACCOUNT_ID
  const imageUrl = process.env.INSTAGRAM_DEFAULT_IMAGE_URL

  if (!accessToken || !accountId) {
    return { success: false, error: 'Instagram credentials not configured' }
  }

  if (!imageUrl) {
    return { success: false, error: 'No default image URL configured for Instagram' }
  }

  try {
    // Step 1: Create media container
    const containerRes = await fetch(
      `https://graph.facebook.com/v19.0/${accountId}/media`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          image_url: imageUrl,
          caption,
          access_token: accessToken,
        }),
      }
    )
    const container = await containerRes.json()
    if (!container.id) return { success: false, error: `Container creation failed: ${JSON.stringify(container)}` }

    // Step 2: Publish
    const publishRes = await fetch(
      `https://graph.facebook.com/v19.0/${accountId}/media_publish`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          creation_id: container.id,
          access_token: accessToken,
        }),
      }
    )
    const pub = await publishRes.json()
    if (!pub.id) return { success: false, error: `Publish failed: ${JSON.stringify(pub)}` }

    return { success: true }
  } catch (e: any) {
    return { success: false, error: e.message }
  }
}

