async function createTikTokDraft(caption: string): Promise<{ success: boolean; error?: string }> {
  const clientKey = process.env.TIKTOK_CLIENT_KEY
  const accessToken = process.env.TIKTOK_ACCESS_TOKEN

  if (!clientKey || !accessToken) {
    return { success: false, error: 'TikTok credentials not configured' }
  }

  // TikTok requires a video file — we create a text-to-video style post via their API
  // For now, we initiate an upload session so the user just needs to add the video file and publish
  try {
    const res = await fetch('https://open.tiktokapis.com/v2/post/publish/inbox/video/init/', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${accessToken}`,
        'Content-Type': 'application/json; charset=UTF-8',
      },
      body: JSON.stringify({
        post_info: {
          title: caption,
          privacy_level: 'SELF_ONLY', // Draft — only visible to you
          disable_duet: false,
          disable_comment: false,
          disable_stitch: false,
          video_cover_timestamp_ms: 1000,
        },
        source_info: {
          source: 'PULL_FROM_URL',
          video_url: process.env.TIKTOK_DEFAULT_VIDEO_URL || '',
        },
      }),
    })

    const data = await res.json()
    if (data.error?.code && data.error.code !== 'ok') {
      return { success: false, error: `TikTok error: ${data.error.message}` }
    }

    return { success: true }
  } catch (e: any) {
    return { success: false, error: e.message }
  }
}

// ─── Main cron handler ────────────────────────────────────────────────────────

export async function GET(request: Request) {
  // Verify cron secret
  const authHeader = request.headers.get('authorization')
  if (authHeader !== `Bearer ${process.env.CRON_SECRET}`) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  const predictions = await getTodaysPredictions()

  if (predictions.length === 0) {
    return NextResponse.json({ success: true, message: 'No predictions today — nothing posted' })
  }

  const results: Record<string, { success: boolean; error?: string }> = {}

  // ── Twitter ──
  const tweets = buildTweetThread(predictions)
  results.twitter = await postToTwitter(tweets)

  // ── Reddit ──
  const { title, text } = buildRedditPost(predictions)
  results.reddit = await postToReddit(title, text)

  // ── Instagram ──
  const igCaption = buildInstagramCaption(predictions)
  results.instagram = await postToInstagram(igCaption)

  // ── TikTok ──
  const ttCaption = buildTikTokCaption(predictions)
  results.tiktok = await createTikTokDraft(ttCaption)

  console.log('Social post results:', JSON.stringify(results))

  return NextResponse.json({
    success: true,
    predictions_count: predictions.length,
    results,
  })
}
